// line to the other store:
//   auto    - the same product; linking it silently is correct.
//   suggest - plausibly what the user wants (other size, generic title, unknown
//             pack size, out of stock...) but they must confirm.
//   none    - a different product; must never be linked automatically.
// `tag` names the defect class the pair exercises (see the matcher audit):
// N1 extra descriptor words, N3 tokenizer/synonyms, N6 dozen, N7 missing size,
// N8 millilitre, N9 ltr, B1 size mismatch, B2 superset variant, B3 price,
// B5 multipack; brand/variant/class for the hard rejects.

